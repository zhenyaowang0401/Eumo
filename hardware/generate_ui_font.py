"""Build a readable device Latin font from the repository's OFL DM Sans.
Pillow/FreeType rasterization; 4-bit coverage, proportional advances, no TTF runtime.
"""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).parent
source = root.parent/'present/assets/fonts/dm-sans.ttf'
out = ['#pragma once', '// Generated by generate_ui_font.py. DM Sans, SIL OFL 1.1.',
       '// Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
       'struct UiGlyph { unsigned offset; unsigned char width,height,advance; signed char x,y; };']
for size in (12,20,40):
    pixels=13 if size==12 else size
    font=ImageFont.truetype(str(source),pixels)
    font.set_variation_by_axes([pixels,600])
    # Align ink to the label's top, rather than leaving the TTF ascender gap.
    baseline=-font.getbbox('H',anchor='ls')[1]
    data=[]; glyphs=[]
    for code in range(32,127):
        char=chr(code); left,top,right,bottom=font.getbbox(char,anchor='ls')
        width,height=right-left,bottom-top
        im=Image.new('L',(max(1,width),max(1,height)))
        ImageDraw.Draw(im).text((-left,-top),char,font=font,fill=255,anchor='ls')
        values=[round(v/17) for v in im.getdata()] if width and height else []
        glyphs.append((len(data),width,height,round(font.getlength(char)),left,top+baseline))
        if len(values)%2: values.append(0)
        data.extend((values[i]<<4)|values[i+1] for i in range(0,len(values),2))
    out.append(f'static const unsigned char UI_BITS_{size}[] = {{'+','.join(map(str,data))+'};')
    out.append(f'static const UiGlyph UI_GLYPHS_{size}[] = {{'+','.join('{'+','.join(map(str,g))+'}' for g in glyphs)+'};')
out += ['inline const UiGlyph &uiGlyph(unsigned char c,int size=12){ if(c<32||c>126)c=63;return (size==40?UI_GLYPHS_40:size==20?UI_GLYPHS_20:UI_GLYPHS_12)[c-32]; }']
(root/'Eumo169/UiFont.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
(root/'Eumo169/UiFont-OFL.txt').write_text('\n'.join(line.rstrip() for line in (source.parent/'dm-sans-OFL.txt').read_text(encoding='utf8').splitlines())+'\n',encoding='utf8')
print('Generated DM Sans 13/20/40px device font (40px for pairing codes).')
